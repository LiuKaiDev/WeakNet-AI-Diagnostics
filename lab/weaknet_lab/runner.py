def _start_product(state: dict[str, Any], report: CapabilityReport, run_root: Path) -> None:
    resources = ResourceNames.from_state(state["resources"])
    for name in ("daemon-state", "daemon-logs", "daemon-run"):
        path = run_root / name
        path.mkdir(parents=True, exist_ok=True)
        path.chmod(0o777)
    server_ready = run_root / "server.ready"
    server = _start_process(
        _netns_command(report, resources.server_namespace, [
            sys.executable, str(LAB_ROOT / "helpers" / "tcp_server.py"),
            "--bind", state["addresses"]["server"], "--port", str(TCP_PORT),
            "--ready-file", str(server_ready),
        ]),
        run_root / "tcp-server.log",
    )
    _record_process(state, "tcp_server", server)
    _wait_for(server_ready.exists, 5, "TCP workload server")
    daemon_command = _netns_command(
        report, resources.client_namespace,
        [*_daemon_environment(state, run_root), str(report.weaknetd_path)],
    )
    daemon = _start_process(daemon_command, run_root / "weaknetd.log")
    _record_process(state, "weaknetd", daemon)
    cli_env = dict(os.environ)
    cli_env["DBUS_SESSION_BUS_ADDRESS"] = str(state["bus_address"])
    _wait_for(
        lambda: run_bounded([str(report.weaknetctl_path), "status"], check=False, env=cli_env, timeout=3).returncode in (0, 1, 2),
        8,
        "weaknetd D-Bus service",
        interval=0.2,
    )


