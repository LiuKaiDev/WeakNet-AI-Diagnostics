def _apply_fault(state: Mapping[str, Any], report: CapabilityReport, scenario: Scenario) -> None:
    resources = ResourceNames.from_state(state["resources"])
    prefix = _privilege_prefix(report)
    if scenario.fault == "none":
        _debug("no fault requested")
        return
    _debug(f"applying {scenario.fault} inside {resources.server_namespace if scenario.fault.startswith('netem-') else resources.client_namespace}")
    if scenario.fault == "netem-delay":
        delay = int(scenario.fault_options.get("delay_ms", 0))
        if not 1 <= delay <= 5000:
            raise LabError("netem delay must be between 1 and 5000 ms")
        run_bounded([*prefix, "ip", "netns", "exec", resources.server_namespace,
                     "tc", "qdisc", "replace", "dev", resources.server_interface,
                     "root", "netem", "delay", f"{delay}ms"])
    elif scenario.fault == "netem-loss":
        loss = int(scenario.fault_options.get("loss_percent", 0))
        if not 1 <= loss <= 80:
            raise LabError("netem loss must be between 1 and 80 percent")
        run_bounded([*prefix, "ip", "netns", "exec", resources.server_namespace,
                     "tc", "qdisc", "replace", "dev", resources.server_interface,
                     "root", "netem", "loss", f"{loss}%"])
    elif scenario.fault == "remove-default-route":
        run_bounded([*prefix, "ip", "-n", resources.client_namespace, "route", "del",
                     "default", "via", state["addresses"]["server"], "dev",
                     resources.client_interface])
    else:
        raise LabError(f"unsupported fault: {scenario.fault}")


def _remove_fault(state: Mapping[str, Any], report: CapabilityReport, scenario: Scenario) -> None:
    resources = ResourceNames.from_state(state["resources"])
    prefix = _privilege_prefix(report)
    if scenario.fault.startswith("netem-"):
        run_bounded([*prefix, "ip", "netns", "exec", resources.server_namespace,
                     "tc", "qdisc", "del", "dev", resources.server_interface, "root"],
                    check=False)
    elif scenario.fault == "remove-default-route":
        run_bounded([*prefix, "ip", "-n", resources.client_namespace, "route", "replace",
                     "default", "via", state["addresses"]["server"], "dev",
                     resources.client_interface])


def _capture_diagnosis(state: Mapping[str, Any]) -> dict[str, Any]:
    previous = os.environ.get("DBUS_SESSION_BUS_ADDRESS")
    os.environ["DBUS_SESSION_BUS_ADDRESS"] = str(state["bus_address"])
    try:
        from ai.v2.sources.dbus import DbusDiagnosisSource
        snapshot = asyncio.run(DbusDiagnosisSource(timeout_seconds=3).current())
        return snapshot.to_dict()
    finally:
        if previous is None:
            os.environ.pop("DBUS_SESSION_BUS_ADDRESS", None)
        else:
            os.environ["DBUS_SESSION_BUS_ADDRESS"] = previous


def _diagnosis_matches(scenario: Scenario, diagnosis: Mapping[str, Any]) -> bool:
    observed_incidents = {
        item.get("type") for item in diagnosis.get("incidents", []) if isinstance(item, Mapping)
    }
    observed_hypotheses = {
        item.get("type") for item in diagnosis.get("hypotheses", []) if isinstance(item, Mapping)
    }
    return (
        set(scenario.expected_incidents).issubset(observed_incidents)
        and set(scenario.expected_hypothesis_types).issubset(observed_hypotheses)
        and not (observed_hypotheses - set(scenario.allowed_hypothesis_types))
        and diagnosis.get("status") in scenario.allowed_statuses
        and (not scenario.require_nonhealthy_status or diagnosis.get("status") != "Healthy")
    )


def _wait_for_diagnosis(state: Mapping[str, Any], scenario: Scenario) -> tuple[dict[str, Any], int | None]:
    started = time.monotonic()
    if not scenario.expected_incidents and not scenario.expected_hypothesis_types:
        time.sleep(scenario.observation_timeout_seconds)
        return _capture_diagnosis(state), int((time.monotonic() - started) * 1000)
    deadline = started + scenario.observation_timeout_seconds
    last: dict[str, Any] | None = None
    while time.monotonic() < deadline:
        last = _capture_diagnosis(state)
        if _diagnosis_matches(scenario, last):
            return last, int((time.monotonic() - started) * 1000)
        time.sleep(1)
    return last or _capture_diagnosis(state), None


def _wait_for_recovery(state: Mapping[str, Any], scenario: Scenario) -> tuple[bool, int | None]:
    started = time.monotonic()
    deadline = started + scenario.recovery_timeout_seconds
    while time.monotonic() < deadline:
        diagnosis = _capture_diagnosis(state)
        incidents = {
            item.get("type") for item in diagnosis.get("incidents", []) if isinstance(item, Mapping)
        }
        hypotheses = {
            item.get("type") for item in diagnosis.get("hypotheses", []) if isinstance(item, Mapping)
        }
        if not (set(scenario.expected_incidents) & incidents) and not (
            set(scenario.expected_hypothesis_types) & hypotheses
        ):
            return True, int((time.monotonic() - started) * 1000)
        time.sleep(1)
    return False, None


def _cli(state: Mapping[str, Any], report: CapabilityReport, *arguments: str) -> subprocess.CompletedProcess[str]:
    environment = dict(os.environ)
    environment["DBUS_SESSION_BUS_ADDRESS"] = str(state["bus_address"])
    if state.get("ai_port"):
        environment["WEAKNET_AI_PORT"] = str(state["ai_port"])
    return run_bounded(
        [str(report.weaknetctl_path), *arguments], check=False, env=environment, timeout=45,
    )


def _start_ai_runtime(state: dict[str, Any], report: CapabilityReport, run_root: Path) -> tuple[bool, str]:
    provider = os.environ.get("WEAKNET_LLM_PROVIDER", "").lower()
    if not provider:
        return False, "WEAKNET_LLM_PROVIDER is not configured"
    if provider == "dashscope" and not os.environ.get("DASHSCOPE_API_KEY"):
        return False, "DashScope API key is not configured"
    if not report.python_venv or not report.dbus_next:
        return False, "repository .venv runtime dependencies are unavailable"
    port = 18000 + (int(ResourceNames.from_state(state["resources"]).token[:4], 16) % 2000)
    environment = dict(os.environ)
    environment["DBUS_SESSION_BUS_ADDRESS"] = str(state["bus_address"])
    environment["WEAKNET_AI_PORT"] = str(port)
    record = _start_process(
        [str(ROOT / ".venv" / "bin" / "python"), "-m", "ai.v2.runtime"],
        run_root / "ai-runtime.log", env=environment,
    )
    _record_process(state, "ai_runtime", record)
    state["ai_runtime_port"] = port
    _atomic_json(ACTIVE_STATE, state)

    def healthy() -> bool:
        try:
            with urlopen(f"http://127.0.0.1:{port}/health/live", timeout=0.3) as response:
                return response.status == 200
        except OSError:
            return False

    _wait_for(healthy, 8, "AI runtime")
    return True, ""


def _run_cli_with_ai_capture(
    state: dict[str, Any], report: CapabilityReport, mode: str,
) -> tuple[subprocess.CompletedProcess[str], int, dict[str, Any]]:
    capture: dict[str, Any] = {}
    upstream_port = int(state["ai_runtime_port"])
    expected_path = "/v2/explanations/current" if mode == "explain" else "/v2/advice/current"

    class RecordingProxy(BaseHTTPRequestHandler):
        def do_POST(self) -> None:  # noqa: N802 - stdlib handler API
            try:
                length = int(self.headers.get("Content-Length", "0"))
            except ValueError:
                length = -1
            if self.path != expected_path or not 0 <= length <= 1_048_576:
                self.send_error(400)
                return
            request = Request(
                f"http://127.0.0.1:{upstream_port}{self.path}",
                data=self.rfile.read(length),
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            try:
                with urlopen(request, timeout=45) as response:
                    status = int(response.status)
                    body = response.read()
            except HTTPError as error:
                status = int(error.code)
                body = error.read()
            except (OSError, URLError) as error:
                status = 502
                body = json.dumps({
                    "error": {"category": "LabProxyError", "message": str(error)}
                }).encode("utf-8")
            capture["status"] = status
            capture["body"] = body
            self.send_response(status)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, format: str, *args: Any) -> None:
            return

    server = ThreadingHTTPServer(("127.0.0.1", 0), RecordingProxy)
    server.timeout = 50
    proxy_port = int(server.server_address[1])
    state["ai_port"] = proxy_port
    thread = threading.Thread(target=server.handle_request, daemon=True)
    thread.start()
    try:
        option = "--explain" if mode == "explain" else "--advise"
        result = _cli(state, report, "diagnose", option)
    finally:
        thread.join(timeout=1)
        server.server_close()
        state.pop("ai_port", None)
    if "body" not in capture:
        raise LabError("weaknetctl did not issue the expected AI runtime request")
    try:
        payload = json.loads(bytes(capture["body"]).decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise LabError(f"AI runtime response is not valid JSON: {error}") from error
    if not isinstance(payload, dict):
        raise LabError("AI runtime response is not an object")
    return result, int(capture["status"]), payload


def _hypothesis_signature(items: Any) -> list[tuple[str, str]]:
    if not isinstance(items, list):
        return []
    result: list[tuple[str, str]] = []
    for item in items:
        if isinstance(item, Mapping):
            result.append((str(item.get("type", "")), str(item.get("confidence", ""))))
    return sorted(result)


def _run_ai(
    state: dict[str, Any], report: CapabilityReport, run_root: Path,
    mode: str, deterministic_cli: subprocess.CompletedProcess[str], diagnosis: Mapping[str, Any],
) -> dict[str, Any]:
    if mode == "none":
        return {"attempted": False}
    started, reason = _start_ai_runtime(state, report, run_root)
    if not started:
        return {"attempted": False, "mode": mode, "status": "SKIP", "reason": reason}
    result, http_status, payload = _run_cli_with_ai_capture(state, report, mode)
    (run_root / f"weaknetctl-{mode}.txt").write_text(
        result.stdout + result.stderr, encoding="utf-8"
    )
    _atomic_json(run_root / f"ai-{mode}-report.json", payload)
    status_unchanged = payload.get("deterministic_status") == diagnosis.get("status")
    report_signature = _hypothesis_signature(payload.get("hypotheses"))
    diagnosis_signature = _hypothesis_signature(diagnosis.get("hypotheses"))
    type_unchanged = [item[0] for item in report_signature] == [item[0] for item in diagnosis_signature]
    confidence_unchanged = report_signature == diagnosis_signature
    deterministic_exit_unchanged = result.returncode == deterministic_cli.returncode
    if mode == "explain":
        schema_success = http_status == 200 and payload.get("validation_status") == "validated"
        grounded = schema_success and status_unchanged and type_unchanged and confidence_unchanged
        success = grounded and deterministic_exit_unchanged
        return {
            "attempted": True,
            "mode": mode,
            "status": "PASS" if success else "FAIL",
            "schema_success": schema_success,
            "diagnosis_grounding": grounded,
            "authoritative_type_unchanged": type_unchanged,
            "confidence_unchanged": confidence_unchanged,
            "deterministic_exit_unchanged": deterministic_exit_unchanged,
        }
    retrieval_mode = str(payload.get("retrieval_mode", "none"))
    report_status = str(payload.get("status", ""))
    schema_success = http_status == 200 and report_status in {"validated", "not_applicable"}
    invalid_citations = int(payload.get("invalid_citation_count", 0))
    grounding_violations = int(payload.get("grounding_violation_count", 0))
    schema_failures = int(payload.get("schema_failure_count", 0))
    citation_grounding = schema_success and invalid_citations == 0
    diagnosis_grounding = (
        schema_success and grounding_violations == 0 and status_unchanged
        and type_unchanged and confidence_unchanged
    )
    success = (
        diagnosis_grounding and citation_grounding and schema_failures == 0
        and deterministic_exit_unchanged
    )
    return {
        "attempted": True,
        "mode": mode,
        "status": "PASS" if success else "FAIL",
        "report_status": report_status,
        "schema_success": schema_success and schema_failures == 0,
        "diagnosis_grounding": diagnosis_grounding,
        "citation_grounding": citation_grounding,
        "invalid_citation_count": invalid_citations,
        "uncited_knowledge_claim_count": grounding_violations,
        "forbidden_overclaim_count": grounding_violations,
        "authoritative_type_unchanged": type_unchanged,
        "confidence_unchanged": confidence_unchanged,
        "deterministic_exit_unchanged": deterministic_exit_unchanged,
        "retrieval_mode": retrieval_mode,
    }


def _resources_present(resources: ResourceNames) -> bool:
    try:
        namespace_result = run_bounded(["ip", "netns", "list"], check=False, timeout=5)
    except (OSError, LabError):
        return True
    namespaces = {line.split()[0] for line in namespace_result.stdout.splitlines() if line.split()}
    if resources.client_namespace in namespaces or resources.server_namespace in namespaces:
        return True
    for interface in (resources.client_interface, resources.server_interface):
        try:
            if run_bounded(
                ["ip", "link", "show", "dev", interface], check=False, timeout=5,
            ).returncode == 0:
                return True
        except (OSError, LabError):
            return True
    return False


def cleanup_lab(
    state_path: Path = ACTIVE_STATE, *, report: CapabilityReport | None = None,
) -> list[str]:
    state = _load_state(state_path)
    if state is None:
        return []
    resources = ResourceNames.from_state(state["resources"])
    actions: list[str] = []
    for name in ("ai_runtime", "tcp_load", "weaknetd", "tcp_server", "dbus"):
        record = state.get("processes", {}).get(name)
        if isinstance(record, Mapping):
            _stop_owned_process(record)
            actions.append(f"stopped {name}")
    capability_report = report or detect_capabilities(ROOT)
    if capability_report.privileged:
        prefix = _privilege_prefix(capability_report)
        for namespace in (resources.client_namespace, resources.server_namespace):
            run_bounded([*prefix, "ip", "netns", "del", namespace], check=False, timeout=10)
            actions.append(f"removed {namespace}")
        for interface in (resources.client_interface, resources.server_interface):
            run_bounded([*prefix, "ip", "link", "del", interface], check=False, timeout=10)
    else:
        actions.append("network cleanup requires privilege")
    if not _resources_present(resources):
        try:
            state_path.unlink()
        except FileNotFoundError:
            pass
    else:
        actions.append("retained state for cleanup retry")
    for action in actions:
        _debug(action)
    return actions


def _new_state(scenario: Scenario) -> tuple[dict[str, Any], Path]:
    if ACTIVE_STATE.exists():
        raise LabError("a lab is already active; run './lab/weaknet-lab down' first")
    resources = ResourceNames.create()
    run_id = f"{scenario.scenario_id}-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}-{resources.token}"
    run_root = OUTPUT_ROOT / run_id
    run_root.mkdir(parents=True, exist_ok=False)
    state: dict[str, Any] = {
        "schema_version": "weaknet.lab.state.v1",
        "run_id": run_id,
        "scenario": scenario.scenario_id,
        "created_at": utc_now(),
        "resources": resources.to_dict(),
        "run_root": str(run_root.resolve()),
        "processes": {},
        "phase": "allocating",
    }
    _atomic_json(ACTIVE_STATE, state)
    _debug(f"allocated run {run_id} at {run_root}")
    _debug(
        f"resources: {resources.client_namespace}, {resources.server_namespace}, "
        f"{resources.client_interface}, {resources.server_interface}"
    )
    return state, run_root


def _bring_up(scenario: Scenario, report: CapabilityReport) -> tuple[dict[str, Any], Path]:
    state, run_root = _new_state(scenario)
    _start_bus(state, run_root)
    _setup_topology(state, report)
    _start_product(state, report, run_root)
    if scenario.workload == "tcp-echo":
        _start_workload(state, report, run_root)
    state["phase"] = "warmup"
    _atomic_json(ACTIVE_STATE, state)
    if scenario.warmup_seconds:
        time.sleep(scenario.warmup_seconds)
    _apply_fault(state, report, scenario)
    state["phase"] = "fault-active"
    state["fault_activated_at"] = utc_now()
    _atomic_json(ACTIVE_STATE, state)
    return state, run_root


def _write_result(run_root: Path, result: Mapping[str, Any]) -> None:
    validate_evaluation(result)
    _atomic_json(run_root / "evaluation.json", result)


def _print_result(result: Mapping[str, Any]) -> None:
    print(f"[scenario] {result['scenario']}")
    print(f"[setup] {result['setup'].upper()}")
    if result["result"] == "SKIP":
        print(f"[result] SKIP: {', '.join(result.get('skip_reasons', []))}")
        return
    for incident in result["observed_incidents"]:
        print(f"[incident] {incident}")
    for hypothesis in result["observed_hypotheses"]:
        print(f"[root cause] {hypothesis}")
    print(f"[status] {result['status']}")
    if result["detection_latency_ms"] is not None:
        print(f"[detection] {result['detection_latency_ms'] / 1000:.1f}s")
    if result["recovered"] is not None:
        label = "PASS" if result["recovered"] else "FAIL"
        detail = f" in {result['recovery_latency_ms'] / 1000:.1f}s" if result["recovery_latency_ms"] is not None else ""
        print(f"[recovery] {label}{detail}")
    ai = result["ai"]
    print(f"[ai] {ai.get('status', 'disabled') if ai.get('attempted') else ai.get('status', 'disabled')}")
    print(f"[result] {result['result']}")


