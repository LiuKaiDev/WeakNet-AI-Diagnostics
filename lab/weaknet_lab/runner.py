def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="weaknet-lab")
    parser.add_argument("--verbose", action="store_true", help="show additional orchestration details")
    subparsers = parser.add_subparsers(dest="command", required=True)
    subparsers.add_parser("list", help="list available scenarios").set_defaults(handler=command_list)
    subparsers.add_parser("doctor", help="report lab prerequisites without exposing secrets").set_defaults(handler=command_doctor)
    up = subparsers.add_parser("up", help="create and leave a scenario running")
    up.add_argument("scenario")
    up.set_defaults(handler=command_up)
    subparsers.add_parser("status", help="show active lab state").set_defaults(handler=command_status)
    run = subparsers.add_parser("run", help="run, evaluate, and clean up a scenario")
    run.add_argument("scenario")
    ai = run.add_mutually_exclusive_group()
    ai.add_argument("--explain", dest="ai_mode", action="store_const", const="explain")
    ai.add_argument("--advise", dest="ai_mode", action="store_const", const="advise")
    ai.add_argument("--no-ai", dest="ai_mode", action="store_const", const="none")
    run.set_defaults(handler=command_run, ai_mode="none")
    subparsers.add_parser("down", help="remove only the active lab's resources").set_defaults(handler=command_down)
    subparsers.add_parser("cleanup", help="idempotent alias for down").set_defaults(handler=command_down)
    fixture = subparsers.add_parser("fixture-demo", help="run a clearly labeled offline AI simulation")
    fixture.add_argument("--mode", choices=("explain", "advise"), default="advise")
    fixture.set_defaults(handler=command_fixture_demo)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    global VERBOSE
    parser = build_parser()
    arguments = parser.parse_args(argv)
    VERBOSE = bool(arguments.verbose)
    if getattr(arguments, "ai_mode", "none") not in AI_MODES:
        parser.error("invalid AI mode")
    try:
        return int(arguments.handler(arguments))
    except KeyboardInterrupt:
        print("weaknet-lab: interrupted", file=sys.stderr)
        return 130
    except (LabError, ValueError) as error:
        print(f"weaknet-lab: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
