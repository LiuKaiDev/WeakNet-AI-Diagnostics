@dataclass(frozen=True)
class ResourceNames:
    token: str
    client_namespace: str
    server_namespace: str
    client_interface: str
    server_interface: str

    @classmethod
    def create(cls, token: str | None = None) -> "ResourceNames":
        value = token or secrets.token_hex(3)
        if not re.fullmatch(r"[0-9a-f]{6}", value):
            raise ValueError("resource token must contain six lowercase hex characters")
        return cls(
            token=value,
            client_namespace=f"wnlab-c-{value}",
            server_namespace=f"wnlab-s-{value}",
            client_interface=f"wnc-{value}",
            server_interface=f"wns-{value}",
        )

    @classmethod
    def from_state(cls, value: Mapping[str, Any]) -> "ResourceNames":
        result = cls(
            token=str(value.get("token", "")),
            client_namespace=str(value.get("client_namespace", "")),
            server_namespace=str(value.get("server_namespace", "")),
            client_interface=str(value.get("client_interface", "")),
            server_interface=str(value.get("server_interface", "")),
        )
        result.validate()
        return result

    def validate(self) -> None:
        if not re.fullmatch(r"[0-9a-f]{6}", self.token):
            raise LabError("refusing cleanup for an invalid lab token")
        if not OWNED_NAMESPACE.fullmatch(self.client_namespace) or not OWNED_NAMESPACE.fullmatch(
            self.server_namespace
        ):
            raise LabError("refusing cleanup for a non-lab namespace")
        if not OWNED_INTERFACE.fullmatch(self.client_interface) or not OWNED_INTERFACE.fullmatch(
            self.server_interface
        ):
            raise LabError("refusing cleanup for a non-lab interface")
        expected = ResourceNames.create(self.token)
        if self != expected:
            raise LabError("lab resource names do not share one ownership token")

    def to_dict(self) -> dict[str, str]:
        return {
            "token": self.token,
            "client_namespace": self.client_namespace,
            "server_namespace": self.server_namespace,
            "client_interface": self.client_interface,
            "server_interface": self.server_interface,
        }


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def run_bounded(
    command: Sequence[str], *, timeout: float = 10, check: bool = True,
    env: Mapping[str, str] | None = None,
) -> subprocess.CompletedProcess[str]:
    try:
        result = subprocess.run(
            list(command), check=False, capture_output=True, text=True,
            timeout=timeout, env=dict(env) if env is not None else None,
        )
    except subprocess.TimeoutExpired as error:
        raise CommandTimedOut(f"command timed out after {timeout:g}s: {command[0]}") from error
    if check and result.returncode != 0:
        detail = (result.stderr or result.stdout).strip().splitlines()
        message = detail[-1] if detail else f"exit {result.returncode}"
        raise LabError(f"command failed: {command[0]}: {message}")
    return result


def _process_start_time(pid: int) -> str | None:
    try:
        return Path(f"/proc/{pid}/stat").read_text(encoding="utf-8").split()[21]
    except (OSError, IndexError):
        return None


def _same_process(pid: int, start_time: str | None) -> bool:
    return start_time is not None and _process_start_time(pid) == start_time


def _stop_owned_process(record: Mapping[str, Any], timeout: float = 3) -> None:
    try:
        pid = int(record["pid"])
        start_time = str(record["start_time"])
    except (KeyError, TypeError, ValueError):
        return
    if not _same_process(pid, start_time):
        return
    try:
        os.killpg(pid, signal.SIGTERM)
    except (ProcessLookupError, PermissionError):
        return
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if not _same_process(pid, start_time):
            return
        time.sleep(0.05)
    if _same_process(pid, start_time):
        try:
            os.killpg(pid, signal.SIGKILL)
        except (ProcessLookupError, PermissionError):
            pass


def _atomic_json(path: Path, value: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    temporary.replace(path)


def _load_state(path: Path = ACTIVE_STATE) -> dict[str, Any] | None:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None
    except (OSError, json.JSONDecodeError) as error:
        raise LabError(f"cannot read lab state: {error}") from error
    if not isinstance(value, dict):
        raise LabError("lab state is not an object")
    ResourceNames.from_state(value.get("resources", {}))
    return value


def _privilege_prefix(report: CapabilityReport) -> list[str]:
    if os.geteuid() == 0 or report.privilege_reason.startswith("effective"):
        return []
    if report.privilege_reason == "passwordless sudo available":
        return ["sudo", "-n"]
    raise LabError(report.privilege_reason)


def _privileged(report: CapabilityReport, command: Sequence[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
    return run_bounded([*_privilege_prefix(report), *command], **kwargs)


def _netns_command(report: CapabilityReport, namespace: str, command: Sequence[str]) -> list[str]:
    if not OWNED_NAMESPACE.fullmatch(namespace):
        raise LabError("refusing to enter a non-lab namespace")
    return [*_privilege_prefix(report), "ip", "netns", "exec", namespace, *command]


def _start_process(
    command: Sequence[str], log_path: Path, *, env: Mapping[str, str] | None = None,
) -> dict[str, Any]:
    log_path.parent.mkdir(parents=True, exist_ok=True)
    stream = log_path.open("ab", buffering=0)
    try:
        process = subprocess.Popen(
            list(command), stdin=subprocess.DEVNULL, stdout=stream, stderr=subprocess.STDOUT,
            env=dict(env) if env is not None else None, start_new_session=True,
        )
    finally:
        stream.close()
    start_time = _process_start_time(process.pid)
    if start_time is None:
        raise LabError(f"failed to track process: {command[0]}")
    _debug(f"started {Path(command[0]).name} pid={process.pid} log={log_path}")
    return {"pid": process.pid, "start_time": start_time, "command": Path(command[0]).name}


def _record_process(state: dict[str, Any], name: str, record: Mapping[str, Any]) -> None:
    state.setdefault("processes", {})[name] = dict(record)
    _atomic_json(ACTIVE_STATE, state)


def _scenario_path(scenario_id: str) -> Path:
    if not re.fullmatch(r"[a-z0-9-]+", scenario_id):
        raise LabError("invalid scenario ID")
    path = SCENARIO_ROOT / f"{scenario_id}.json"
    if not path.is_file():
        raise LabError(f"unknown scenario: {scenario_id}")
    return path


def scenarios() -> list[Scenario]:
    return [load_scenario(path) for path in sorted(SCENARIO_ROOT.glob("*.json"))]


def _lab_addresses(token: str) -> tuple[str, str, str]:
    octet = 64 + (int(token[:2], 16) % 128)
    return f"198.18.{octet}.1", f"198.18.{octet}.2", f"198.18.{octet}.0/30"


def _wait_for(predicate: Any, timeout: float, description: str, interval: float = 0.1) -> None:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if predicate():
            return
        time.sleep(interval)
    raise LabError(f"timed out waiting for {description}")


def _start_bus(state: dict[str, Any], run_root: Path) -> str:
    socket_path = run_root / "bus.sock"
    address = f"unix:path={socket_path}"
    record = _start_process(
        ["dbus-daemon", "--session", "--nofork", f"--address={address}", "--nopidfile"],
        run_root / "dbus.log",
    )
    _record_process(state, "dbus", record)
    _wait_for(socket_path.exists, 5, "lab session D-Bus socket")
    state["bus_address"] = address
    _atomic_json(ACTIVE_STATE, state)
    return address


def _setup_topology(state: dict[str, Any], report: CapabilityReport) -> None:
    resources = ResourceNames.from_state(state["resources"])
    client_ip, server_ip, subnet = _lab_addresses(resources.token)
    state["addresses"] = {"client": client_ip, "server": server_ip, "subnet": subnet}
    _atomic_json(ACTIVE_STATE, state)
    prefix = _privilege_prefix(report)
    commands = [
        [*prefix, "ip", "netns", "add", resources.client_namespace],
        [*prefix, "ip", "netns", "add", resources.server_namespace],
        [*prefix, "ip", "link", "add", resources.client_interface, "type", "veth", "peer", "name", resources.server_interface],
        [*prefix, "ip", "link", "set", resources.client_interface, "netns", resources.client_namespace],
        [*prefix, "ip", "link", "set", resources.server_interface, "netns", resources.server_namespace],
        [*prefix, "ip", "-n", resources.client_namespace, "link", "set", "lo", "up"],
        [*prefix, "ip", "-n", resources.server_namespace, "link", "set", "lo", "up"],
        [*prefix, "ip", "-n", resources.client_namespace, "addr", "add", f"{client_ip}/30", "dev", resources.client_interface],
        [*prefix, "ip", "-n", resources.server_namespace, "addr", "add", f"{server_ip}/30", "dev", resources.server_interface],
        [*prefix, "ip", "-n", resources.client_namespace, "link", "set", resources.client_interface, "up"],
        [*prefix, "ip", "-n", resources.server_namespace, "link", "set", resources.server_interface, "up"],
        [*prefix, "ip", "-n", resources.client_namespace, "route", "add", "default", "via", server_ip, "dev", resources.client_interface],
    ]
    for command in commands:
        run_bounded(command, timeout=10)


