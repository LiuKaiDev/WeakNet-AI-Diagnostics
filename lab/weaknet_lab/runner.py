def command_run(arguments: argparse.Namespace) -> int:
    scenario = load_scenario(_scenario_path(arguments.scenario))
    report = detect_capabilities(ROOT)
    run_id = f"{scenario.scenario_id}-skip-{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}"
    missing = missing_capabilities(scenario, report)
    if missing:
        result = skipped_evaluation(scenario, run_id, [f"missing capability: {item}" for item in missing])
        run_root = OUTPUT_ROOT / run_id
        run_root.mkdir(parents=True, exist_ok=True)
        _write_result(run_root, result)
        _print_result(result)
        return 0
    state: dict[str, Any] | None = None
    try:
        state, run_root = _bring_up(scenario, report)
        diagnosis, latency = _wait_for_diagnosis(state, scenario)
        deterministic_cli = _cli(state, report, "diagnose")
        (run_root / "weaknetctl-diagnose.txt").write_text(
            deterministic_cli.stdout + deterministic_cli.stderr, encoding="utf-8"
        )
        ai = _run_ai(
            state, report, run_root, arguments.ai_mode, deterministic_cli, diagnosis,
        )
        recovered: bool | None = None
        recovery_latency: int | None = None
        if scenario.recovery:
            _remove_fault(state, report, scenario)
            state["phase"] = "recovering"
            _atomic_json(ACTIVE_STATE, state)
            recovered, recovery_latency = _wait_for_recovery(state, scenario)
        result = evaluate_diagnosis(
            scenario, diagnosis, detection_latency_ms=latency,
            recovered=recovered, recovery_latency_ms=recovery_latency,
            run_id=state["run_id"], ai=ai,
        )
        _write_result(run_root, result)
        _print_result(result)
        return 0 if result["result"] == "PASS" else 1
    except (LabError, ValueError) as error:
        print(f"[result] FAIL: {error}", file=sys.stderr)
        return 1
    finally:
        if state is not None or ACTIVE_STATE.exists():
            cleanup_lab(report=report)


